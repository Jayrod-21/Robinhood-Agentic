#!/usr/bin/env bash
# pick_ports.sh — choose two genuinely-free, random TCP ports for the dashboard.
#
# The user asked for fresh, random ports that are actually verified free — not a fixed pair, and
# not just "probably free". Each candidate is drawn at random and accepted ONLY if it passes three
# independent free-checks, and we try up to 15 random draws per port before giving up:
#
#   1. socket bind   — Python binds 0.0.0.0:<port> with SO_REUSEADDR OFF (fails if anything holds it)
#   2. ss listeners  — the port is not in `ss -ltn`'s listening set
#   3. docker ports  — the port is not published by any running container (`docker ps`)
#
# Backend and frontend ports are drawn independently and required to differ; the frontend is also
# re-checked against the just-chosen backend port. Result is written to `.env.ports` (consumed by
# docker-compose) and echoed. Re-running yields different ports, proving the draw is random.
#
# Range: 20000–32767, deliberately kept BELOW the conventional Linux ephemeral floor (32768) so a
# chosen port can't collide with a kernel-allocated outbound socket. The per-candidate bind test
# verifies each port is free *at check time*; a small TOCTOU window remains between that check and
# `docker compose` binding the port, so this verifies freedom at check time, not a guarantee for all
# time. For a single-user localhost dev tool that residual race is acceptable.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT_FILE="${PROJECT_DIR}/.env.ports"

PORT_MIN=20000
PORT_MAX=32767   # below the conventional ephemeral floor (32768) — see header
MAX_ATTEMPTS=15

# --- docker port set (best-effort; empty if daemon down) --------------------------------------
docker_published_ports() {
  command -v docker >/dev/null 2>&1 || return 0
  docker ps --format '{{.Ports}}' 2>/dev/null \
    | grep -oE ':[0-9]+->' | tr -dc '0-9\n' || true
}

DOCKER_PORTS="$(docker_published_ports)"

# --- ss listening set -------------------------------------------------------------------------
ss_listening_ports() {
  ss -ltn 2>/dev/null | awk 'NR>1 {print $4}' | grep -oE '[0-9]+$' || true
}

# --- single candidate free? -------------------------------------------------------------------
port_is_free() {
  local port="$1"

  # (2) ss listeners
  if printf '%s\n' "${SS_PORTS}" | grep -qx "${port}"; then
    return 1
  fi
  # (3) docker published
  if printf '%s\n' "${DOCKER_PORTS}" | grep -qx "${port}"; then
    return 1
  fi
  # (1) authoritative bind test — no SO_REUSEADDR, so a held port really fails
  python3 - "${port}" <<'PY'
import socket, sys
port = int(sys.argv[1])
s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
try:
    s.bind(("0.0.0.0", port))
except OSError:
    sys.exit(1)
finally:
    s.close()
sys.exit(0)
PY
}

# --- pick one free random port, excluding any in $1 (space-separated) --------------------------
pick_one() {
  local exclude="$1"
  local attempt port
  for attempt in $(seq 1 "${MAX_ATTEMPTS}"); do
    # secrets.randbelow → cryptographically-strong fresh draw each attempt
    port="$(python3 -c "import secrets; print(${PORT_MIN} + secrets.randbelow(${PORT_MAX}-${PORT_MIN}+1))")"
    case " ${exclude} " in *" ${port} "*) continue ;; esac
    if port_is_free "${port}"; then
      printf '%s' "${port}"
      return 0
    fi
  done
  return 1
}

# Refresh the listening set once per run (it can change between the two picks, but a final
# re-verify below closes that gap).
SS_PORTS="$(ss_listening_ports)"

BACKEND_PORT="$(pick_one "")" || {
  echo "pick_ports: no free backend port in ${MAX_ATTEMPTS} random draws (${PORT_MIN}-${PORT_MAX})" >&2
  exit 1
}

FRONTEND_PORT="$(pick_one "${BACKEND_PORT}")" || {
  echo "pick_ports: no free frontend port in ${MAX_ATTEMPTS} random draws (${PORT_MIN}-${PORT_MAX})" >&2
  exit 1
}

# Final guard: re-verify both are still free and distinct right before we commit them. Refresh both
# the ss and docker snapshots so a listener/container started since the initial draw is caught.
SS_PORTS="$(ss_listening_ports)"
DOCKER_PORTS="$(docker_published_ports)"
if [[ "${BACKEND_PORT}" == "${FRONTEND_PORT}" ]] \
   || ! port_is_free "${BACKEND_PORT}" || ! port_is_free "${FRONTEND_PORT}"; then
  echo "pick_ports: chosen ports no longer free on re-verify — re-run" >&2
  exit 1
fi

cat > "${OUT_FILE}" <<EOF
# Generated by bin/pick_ports.sh — fresh random free ports. Do not commit.
BACKEND_PORT=${BACKEND_PORT}
FRONTEND_PORT=${FRONTEND_PORT}
EOF

echo "Picked free ports → backend=${BACKEND_PORT} frontend=${FRONTEND_PORT}"
echo "Wrote ${OUT_FILE}"
