#!/usr/bin/env bash
# pick_ports.sh — choose two genuinely-free, random TCP ports for the dashboard.
#
# The dashboard is deliberately ephemeral: fresh random ports every run, not a fixed pair, so it can
# never collide with another stack on this box. The three-check verification lives in
# bin/lib_ports.sh (socket bind + ss listeners + docker published — see that file's header for why
# each is needed).
#
# Backend and frontend ports are drawn independently and required to differ; both are re-verified
# immediately before being committed, so a listener or container that appeared mid-run is caught.
#
# Result is written to `.env.ports` (consumed by docker-compose) and echoed. Re-running yields
# different ports, proving the draw is random.
#
# Contrast with bin/pick_db_port.sh, which picks ONCE and persists — a database's port must stay
# stable across restarts, whereas the dashboard's is intentionally not.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT_FILE="${PROJECT_DIR}/.env.ports"

# shellcheck source=bin/lib_ports.sh
source "${SCRIPT_DIR}/lib_ports.sh"

refresh_port_snapshots

BACKEND_PORT="$(pick_free_port "")" || {
  echo "pick_ports: no free backend port in ${MAX_ATTEMPTS} random draws (${PORT_MIN}-${PORT_MAX})" >&2
  exit 1
}

FRONTEND_PORT="$(pick_free_port "${BACKEND_PORT}")" || {
  echo "pick_ports: no free frontend port in ${MAX_ATTEMPTS} random draws (${PORT_MIN}-${PORT_MAX})" >&2
  exit 1
}

# Final guard: re-verify both are still free and distinct right before we commit them. Refresh the
# snapshots so a listener/container started since the initial draw is caught.
refresh_port_snapshots
if [[ "${BACKEND_PORT}" == "${FRONTEND_PORT}" ]] \
   || ! port_is_free "${BACKEND_PORT}" || ! port_is_free "${FRONTEND_PORT}"; then
  echo "pick_ports: chosen ports no longer free on re-verify — re-run" >&2
  exit 1
fi

cat > "${OUT_FILE}" <<EOF
# Generated by bin/pick_ports.sh — fresh random free ports. Do not commit.
BACKEND_PORT=${BACKEND_PORT}
FRONTEND_PORT=${FRONTEND_PORT}
EOF

echo "Picked free ports → backend=${BACKEND_PORT} frontend=${FRONTEND_PORT}"
echo "Wrote ${OUT_FILE}"
